import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
import os
from typing import List

def plot_s_parameters_db(file_paths: List[str], output_image_name: str = 's_parameter_magnitude_plot.png'):
    """
    Reads averaged polar S-parameter data from multiple files, converts magnitude to dB,
    and generates two rectangular plots: S11 (Return Loss) vs. Frequency.

    :param file_paths: A list of full paths to the CSV files generated by the data_converter module.
    :param output_image_name: The filename for the resulting plot image (saved in the current directory).
    """
    
    # 1. Prepare Data for Plotting
    all_data = []
    
    for file_path in file_paths:
        try:
            df = pd.read_csv(file_path)

            #Read the angle from the csv file
            angle = df['Angle_deg'].iloc[0] # one angle per file
            
            # --- Convert Magnitude to dB ---
            # S(dB) = 20 * log10(|S|)
            df['S11_dB'] = 20 * np.log10(df['S11_Mag'])    
            df['Angle'] = angle
            all_data.append(df)
            
        except Exception as e:
            print(f"Error reading or processing {file_path}: {e}")
            continue

    if not all_data:
        print("No valid data files were processed for plotting.")
        return

    # Combine all data into a single DataFrame
    combined_df = pd.concat(all_data, ignore_index=True)

    # Ensure numeric type and convert Hz → MHz
    combined_df['Frequency'] = pd.to_numeric(combined_df['Frequency'], errors='coerce') / 1e6  

    # Determine global frequency range in MHz
    freq_min = 1500
    freq_max = combined_df['Frequency'].max()
    
    # 2. Generate Rectangular Plots
    # Create a figure with two subplots stacked vertically
    fig, ax_s11 = plt.subplots(1, 1, figsize=(12, 7))

    # --- Plot S11 (Return Loss) ---
    for angle, group in combined_df.groupby('Angle'):
        ax_s11.plot(group['Frequency'], group['S11_dB'], label=f"{angle} degree", linewidth=2)
 
    ax_s11.set_title(r'$S_{11}$ Magnitude (Return Loss) vs. Frequency', fontsize=14)
    ax_s11.set_xlabel('Frequency', fontsize=12)
    ax_s11.set_ylabel(r'Magnitude ($\text{dB}$)', fontsize=12)

    # --- THE STARTING POINT FIX ---
    ax_s11.set_xlim(left=freq_min, right=freq_max)

    # --- High-Resolution Grid and Ticks (X-Axis) ---
    # Major grid lines every 10 MHz, Minor every 5 MHz
    ax_s11.xaxis.set_major_locator(ticker.MultipleLocator(10))
    ax_s11.xaxis.set_minor_locator(ticker.MultipleLocator(5))

    # --- High-Resolution Grid and Ticks (Y-Axis) ---
    # Major grid lines every 10 dB, Minor every 5 dB
    ax_s11.yaxis.set_major_locator(ticker.MultipleLocator(10))
    ax_s11.yaxis.set_minor_locator(ticker.MultipleLocator(5))
  
    # --- Styling the Grid ---
    # Major grid: Solid and darker
    ax_s11.grid(True, which='major', linestyle='-', linewidth=0.7, color='gray', alpha=0.6)
    # Minor grid: Dotted and lighter
    ax_s11.grid(True, which='minor', linestyle=':', linewidth=0.5, color='gray', alpha=0.4)

    # Tick mark styling
    ax_s11.tick_params(axis='both', which='major', labelsize=10, length=7)
    ax_s11.tick_params(axis='both', which='minor', length=4)

    ax_s11.legend(loc='lower right', fontsize=10, frameon=True, shadow=True)

    # General Plot Adjustments
    plt.tight_layout()
    plt.show() 



